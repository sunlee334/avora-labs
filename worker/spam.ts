/**
 * 봇이 낸 것인지.
 *
 * ── 왜 CAPTCHA 가 아닌가 ────────────────────────────────────
 * 이 사이트의 폼은 전부 "이메일 하나 남기기" 수준입니다. 거기에 퍼즐을 붙이면
 * 막는 봇보다 잃는 사람이 많습니다. 아래 두 가지는 사용자가 존재를 알아채지도
 * 못하고, 실패해도 조용히 버려집니다.
 *
 * ── 왜 이것이 필요한가 ──────────────────────────────────────
 * 12월에 **명단 800명** 을 기준으로 다음 판단을 하기로 했습니다. 봇이 100건을
 * 넣으면 그 판단이 틀어집니다. 속도 제한(rate-limit.ts)은 같은 아이피에서
 * 쏟아지는 것을 막지만, 느리게 흩어 넣는 것은 잡지 못합니다.
 */

/** 화면에 없는 칸의 이름. 폼과 워커가 같은 값을 써야 합니다. */
export const HONEYPOT_FIELD = 'website';

/**
 * 봇이 채워 넣은 흔적이 있는가.
 *
 * 사람에게는 보이지도, 탭으로 닿지도, 스크린리더에 읽히지도 않는 칸입니다.
 * 값이 들어 있으면 폼을 기계가 채웠다는 뜻입니다.
 *
 * 이름을 `website` 로 둔 이유: 봇은 흔한 이름을 채웁니다. `honeypot` 이라고
 * 적어 두면 요즘 봇은 건너뜁니다.
 */
export function looksAutomated(body: Record<string, unknown>): boolean {
  const trap = body[HONEYPOT_FIELD];
  return typeof trap === 'string' && trap.trim() !== '';
}

/**
 * 사람이 채우기에 너무 빨랐는가.
 *
 * 화면이 뜬 뒤 제출까지 걸린 시간을 봅니다. 이메일 한 칸을 채우는 데에도
 * 사람은 최소 몇 초가 걸립니다.
 *
 * ── 왜 절대 시각이 아니라 경과 시간인가 ─────────────────────
 * 처음에는 화면이 뜬 **시각** 을 보내고 서버 시계와 뺐습니다. 그러면 기기
 * 시계가 앞선 사람의 정상 제출이 조용히 버려집니다 — 시계가 몇 분 어긋난
 * 휴대폰은 드물지 않고, 그 사람은 아무리 다시 눌러도 접수되지 않습니다.
 * 브라우저가 직접 잰 경과 시간을 보내면 두 시계를 비교할 일이 없습니다.
 *
 * ── 2초인 이유 ──────────────────────────────────────────────
 * 더 올리면 브라우저 자동완성으로 한 번에 채우는 사람이 걸립니다 — 그쪽이
 * 봇보다 훨씬 흔합니다.
 *
 * 값이 없거나 이상하면 **통과시킵니다.** 시간을 못 재는 상황(스크립트 차단,
 * 오래된 브라우저)에서 사람을 막는 것보다, 봇 몇을 놓치는 편이 낫습니다.
 */
export const MIN_FILL_MS = 2000;

export function tooFast(body: Record<string, unknown>, _now?: Date): boolean {
  const elapsed = Number(body.elapsedMs);
  if (!Number.isFinite(elapsed) || elapsed < 0) return false;
  return elapsed < MIN_FILL_MS;
}
