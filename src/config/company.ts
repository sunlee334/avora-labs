/**
 * 회사 소개에 쓸 값.
 *
 * ── 왜 i18n 이 아니라 여기인가 ──────────────────────────────
 * 창업 배경과 대표자 사진은 **담당자에게 받아야 하는 것** 이고, 아직 오지
 * 않았습니다. i18n 에 두면 `check:i18n` 이 5개 언어 모두를 요구하므로 지어낸
 * 문장을 채워 넣게 됩니다. 여기 두면 **비어 있는 채로 통과** 하고, 비어 있는
 * 동안에는 그 블록이 화면에 아예 나오지 않습니다.
 *
 * `src/config/site.ts` 의 `BUSINESS.mailOrderNumber` 와 같은 규칙입니다 —
 * 없는 것을 지어내는 것은 없는 것보다 나쁩니다.
 *
 * ── 담당자에게 받을 것 (J5) ────────────────────────────────
 *   1. 대표자 사진 1장 — 얼굴이 보이는 것. **스톡 금지**
 *   2. 왜 선케어를 시작했는가 — 3~4문장
 *   3. AVORA LABS 를 한 문장으로
 *   4. 팀 규모를 어떻게 표현할지 (예: "두 사람이 시작했습니다")
 *
 * 2·4 는 아래 FOUNDER_STORY 에, 1 은 FOUNDER_PHOTO 에 넣습니다. 3 은 이미
 * 공개된 문구(`home.company.lead`)가 있어 그것을 쓰고 있습니다.
 */
import type { Locale } from './site';

/**
 * 대표자 사진 파일명. `src/assets/images/` 안의 이름입니다.
 *
 * 값이 있으면 소개 섹션이 **2열(사진 + 글)** 이 되고, 없으면 1열로 남습니다.
 * `.section--split` 의 `auto-fit` 이 그 일을 합니다 — 회색 플레이스홀더 상자를
 * 놓지 않습니다. 빈 회색 사각형은 사진이 없는 것보다 더 허전해 보입니다.
 */
export const FOUNDER_PHOTO: string | null = null;

/**
 * 왜 이 브랜드를 시작했는가. 언어별로 넣습니다.
 *
 * **비어 있으면 그 문단이 나오지 않습니다.** 한 언어만 채워도 그 언어에서만
 * 나옵니다 — 번역이 오는 속도가 달라도 화면이 깨지지 않습니다.
 *
 * ⚠️ 여기에 **지어낸 이야기를 넣지 마세요.** 담당자가 준 문장만 옮깁니다.
 */
export const FOUNDER_STORY: Partial<Record<Locale, string>> = {};

/**
 * 대표자 사진의 대체 텍스트. 언어별로 넣습니다.
 *
 * 사진에 무엇이 보이는지 적습니다 — 회사 슬로건이나 이름이 아니라. 사진이
 * 뜨지 않은 사람과 스크린리더 사용자에게 남는 것이 이 문장입니다.
 * 사진과 함께 담당자에게 받습니다.
 */
export const FOUNDER_PHOTO_ALT: Partial<Record<Locale, string>> = {};

/**
 * 팀 규모를 어떻게 말할 것인가. 언어별로 넣습니다.
 *
 * 지시서가 초안을 주었습니다 — "두 사람이 시작했습니다. 연구소를 차릴 수 없어서
 * 여러분에게 맡기는 것이 아니라, 작기 때문에 기준을 공개하고 판단을 나눌 수
 * 있습니다."
 *
 * ⚠️ **그 문장을 여기 미리 넣지 않았습니다.** 같은 지시서의 확인 항목이
 * "팀 규모 공개 여부와 문구" 를 담당자 몫으로 남겨 두었기 때문입니다. 몇
 * 사람인지는 공개할지 말지가 먼저인 정보이고, 그 판단은 저희 것이 아닙니다.
 *
 * 값이 오면 이 블록이 화면에 나타납니다. 그때까지는 없는 것으로 둡니다 —
 * `FOUNDER_STORY` 와 같은 규칙입니다.
 */
export const TEAM_SIZE: Partial<Record<Locale, string>> = {};

/**
 * 설립 시점.
 *
 * 지시서 B2 는 "2026년 서울에서 시작한" 이라고 적었지만, 같은 문서의 확인
 * 항목이 **"AVORA LABS 설립 연도 — 2026년 서울이 맞는지"** 를 담당자에게
 * 묻고 있습니다. 사업자등록증명이 2026-07-22 발급이라 가깝기는 하지만,
 * 등록일과 "시작한 해" 가 같다고 단정할 근거는 없습니다.
 *
 * 값이 들어오면 `Organization` 구조화 데이터의 `foundingDate` 로 나갑니다.
 * 비어 있으면 그 항목 자체가 빠집니다 — 지어내지 않습니다.
 *
 * ⚠️ 한동안 이 값을 **아무도 읽지 않았습니다.** 주석은 "값이 비어 있으면 그
 * 구절이 문장에서 빠집니다" 라고 적어 두어, 채워 넣으면 화면이 달라질 것처럼
 * 읽혔습니다. 실제로는 채워도 아무 일도 일어나지 않았습니다.
 *
 * 화면 문장이 아니라 구조화 데이터에 붙인 이유는, 문장은 다섯 언어의 번역이
 * 함께 있어야 하지만 `foundingDate` 는 **연도 하나면 되고** 답변엔진이 회사를
 * 하나의 실체로 묶는 데 바로 쓰이기 때문입니다.
 */
export const FOUNDED: string | null = null;
