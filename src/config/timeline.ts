/**
 * 홈 타임라인의 **날짜**.
 *
 * ── 왜 i18n 이 아니라 여기인가 ──────────────────────────────
 * 날짜는 번역되는 것이 아닙니다. 표기(`2026.10` · `Oct 2026` · `10/2026`)는
 * 언어마다 다르니 i18n 에 남지만, **언제인가** 는 하나뿐입니다. 다섯 파일에
 * 같은 값을 적어 두면 언젠가 한 곳만 고쳐집니다.
 *
 * ── 왜 필요해졌나 ─────────────────────────────────────────
 * 전에는 진행 상태가 i18n 의 고정 문자열이었습니다. 첫 항목이 `진행중` 으로
 * 박혀 있었는데, 2026-09-02 기준 검증단 모집은 **아직 시작하지 않았습니다.**
 * `llms.txt` 는 정확하게 "Recruiting opens in October 2026" 라고 적어 두었고,
 * 화면이 그것을 뒤집고 있었습니다 — 답변엔진은 화면을 먼저 읽습니다.
 *
 * 게다가 시간이 지나면 계속 어긋납니다. 11월이 되면 이번에는 블라인드 평가가
 * `예정` 인 채로 남습니다. 상태를 손으로 적는 한 이 화면은 늘 과거의 사실을
 * 말하게 됩니다.
 *
 * ⚠️ 항목 수와 순서가 `i18n` 의 `home.timeline.steps` 와 **같아야 합니다.**
 *    어긋나면 다른 단계의 날짜가 붙습니다. `home-order.spec.ts` 가 그 길이를
 *    확인합니다.
 */

/**
 * 각 단계가 시작하는 시점. `<time datetime>` 에 그대로 들어가는 값이라
 * ISO 8601 이어야 합니다(`2026-10` 은 달, `2027` 은 해 단위로 유효합니다).
 *
 * 마지막 항목이 `2027` 인 이유: 정식 출시는 "2027 상반기" 라 달이 정해지지
 * 않았습니다. 없는 달을 지어내는 대신 해 단위로 둡니다 — 그 해가 시작되면
 * 출시 기간에 들어선 것이 맞습니다.
 */
export const TIMELINE_DATES = ['2026-10', '2026-11', '2026-12', '2027-02', '2027'] as const;

/** 한 단계의 진행 상태. `past` 는 배지를 그리지 않습니다 — 아래 주석 참조. */
export type StepState = 'past' | 'active' | 'planned';

/**
 * 오늘을 기준으로 각 단계가 어디쯤인가.
 *
 * 한 단계는 자기 날짜부터 **다음 단계가 시작하기 전까지** 진행중입니다.
 * 마지막 단계는 다음이 없으므로 자기 날짜 이후로 계속 진행중입니다.
 *
 * ── `past` 에 문구가 없는 이유 ─────────────────────────────
 * "완료" 에 해당하는 말이 다섯 언어 어디에도 없습니다. 새로 지어내면 검수받지
 * 않은 줄이 다섯 개 늘어나고, 그건 이 저장소가 반복해서 피해 온 일입니다.
 * 값이 없으면 라벨도 그리지 않는 규칙(푸터의 사업자 정보와 같은 규칙)을 그대로
 * 적용합니다 — 지나간 단계에 배지가 없는 것은 읽는 데 문제가 되지 않습니다.
 */
export function stepStates(today: Date): StepState[] {
  // `2026-10` < `2026-11` 처럼 ISO 문자열은 사전순 비교가 곧 시간순 비교입니다.
  const now = today.toISOString().slice(0, 10);
  const startsAfter = (date: string) => date > now.slice(0, date.length);

  return TIMELINE_DATES.map((date, i) => {
    if (startsAfter(date)) return 'planned';
    const next = TIMELINE_DATES[i + 1];
    return next && !startsAfter(next) ? 'past' : 'active';
  });
}
