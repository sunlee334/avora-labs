-- 출시 알림 신청 명단.
--
-- 제품 기획안이 이것을 "핵심" 이라고 부릅니다 — 펀딩 오픈 전에 사전 알림
-- 신청자를 모아 초반 달성률을 올리는 것이 목표이고, 그 명단은 "플랫폼에
-- 귀속되지 않는 브랜드 자산" 으로 남습니다. 와디즈에 모인 명단은 와디즈의
-- 것이지만 여기 모인 명단은 우리 것입니다.
--
-- ── 왜 이메일 하나만 받는가 ──────────────────────────────────
-- 출시가 2027년 상반기이고 지금은 처방도 안 정해졌습니다. 이름·관심 활동까지
-- 물으면 칸이 늘어난 만큼 이탈합니다. 이 단계에서 필요한 것은 "연락할 수 있는
-- 주소" 하나뿐이고, 나머지는 실제로 보낼 것이 생겼을 때 물어도 늦지 않습니다.
--
-- ── 동의와 해지를 컬럼으로 남깁니다 ──────────────────────────
-- 광고성 정보 수신은 개인정보 보호법상 동의가 필요하고, 수신 거부 수단을
-- 함께 제공해야 합니다. "동의를 받았다" 를 코드 주석이 아니라 **행에** 남겨야
-- 나중에 증명할 수 있습니다. 그래서 consented_at 을 NOT NULL 로 둡니다 —
-- 동의 없이 들어온 행이 존재할 수 없게 데이터베이스가 막습니다.
--
-- unsubscribe_token 은 메일의 수신거부 링크에 붙습니다. 이메일 주소를 링크에
-- 그대로 실으면 그 주소가 로그·리퍼러·브라우저 기록에 남고, 남의 주소를 넣어
-- 남을 해지시킬 수도 있습니다.
--
-- ── 지운 것이 아니라 내린 것 ────────────────────────────────
-- 해지해도 행을 지우지 않고 unsubscribed_at 을 채웁니다. 지우면 같은 주소가
-- 다시 신청했을 때 "예전에 거부한 사람" 인지 알 수 없고, 그건 다시 보내면 안
-- 되는 사람에게 보내는 사고로 이어집니다. reviews 표에서 status='removed' 로
-- 남기는 것과 같은 이유입니다.

CREATE TABLE IF NOT EXISTS launch_notify (
  id                TEXT PRIMARY KEY,   -- NOTIFY-20260828120000-A1B2C3

  -- 소문자로 정규화해서 넣습니다. 같은 주소가 두 행이 되면 두 번 보냅니다.
  email             TEXT NOT NULL UNIQUE,

  -- 어느 언어 화면에서 신청했는가. 안내 메일을 그 언어로 보내기 위해서입니다.
  locale            TEXT NOT NULL,

  -- 어느 화면에서 왔는가(product · home 등). 어디가 실제로 명단을 만드는지
  -- 알아야 그다음에 무엇을 고칠지 정할 수 있습니다.
  source            TEXT,

  created_at        TEXT NOT NULL,
  -- 광고성 정보 수신 동의 시각. 동의 없는 행은 존재할 수 없습니다.
  consented_at      TEXT NOT NULL,

  unsubscribe_token TEXT NOT NULL UNIQUE,
  unsubscribed_at   TEXT
);

-- 아직 보낼 대상(해지하지 않은 사람)만 빠르게 세고 뽑기 위해서입니다.
CREATE INDEX IF NOT EXISTS idx_launch_notify_active
  ON launch_notify (unsubscribed_at, created_at DESC);
