-- 수신 동의를 갈래별로, 그리고 알림 신청자의 활동 종목.
--
-- 두 가지를 한 파일에 담습니다. 둘 다 "누구에게 무엇을 보낼 것인가" 를 정하는
-- 자료이고, 제품 기획안 9-2·9-3 의 재구매 안내가 이 둘 없이는 작동하지 않습니다.
--
-- ─────────────────────────────────────────────────────────────────────
-- 1. orders.marketing_sms_at — 문자·알림톡 수신 동의 시각
-- ─────────────────────────────────────────────────────────────────────
--
-- **이메일 동의와 별개 항목입니다.** 하나로 묶으면 안 됩니다 — 이메일만 받겠다는
-- 사람에게 문자를 보내는 셈이 되고, 그건 동의를 받은 것이 아닙니다.
--
-- 불리언이 아니라 시각인 이유: "동의했다" 만 남기면 언제 받았는지 증명할 수
-- 없습니다. launch_notify.consented_at 과 같은 방식입니다. NULL 이 미동의입니다.
--
-- 수집 경로는 따로 두지 않습니다. 이 열이 orders 표에 있다는 것 자체가
-- "주문 단계에서 받았다" 는 뜻이고, 다른 경로가 생기면 그때 열을 나눕니다.
ALTER TABLE orders ADD COLUMN marketing_sms_at TEXT;

-- ─────────────────────────────────────────────────────────────────────
-- 2. launch_notify.activities — 주로 하는 활동
-- ─────────────────────────────────────────────────────────────────────
--
-- 왜 받는가: 2026년 10월 러너 검증단 30~50명을 모집할 때(기획안 2-2-2)
-- 이 명단이 출발점입니다. 그때 "달리는 사람" 을 골라내지 못하면 명단 전체에
-- 메일을 뿌려야 하고, 관심 없는 사람에게 보낸 만큼 수신 거부가 늘어납니다.
--
-- **선택 항목입니다.** 이메일만 남기고 가는 사람을 막지 않습니다 — 명단을
-- 만드는 것이 1순위이고, 칸이 늘수록 제출률은 떨어집니다.
--
-- 표를 따로 파지 않고 한 열에 담는 이유: 값이 여섯 개로 고정돼 있고(워커의
-- ACTIVITIES 가 정의처입니다), 우리가 할 일은 "러닝을 고른 사람" 을 뽑는 것
-- 하나뿐입니다. 조인 표를 만들면 읽는 코드가 늘어나는 대신 얻는 것이 없습니다.
--
-- 형식은 쉼표로 이은 슬러그입니다: 'running,climbing'.
-- 부분 일치 검색이 이웃 값을 잘못 잡지 않도록 양끝에도 쉼표를 둡니다:
--   WHERE ',' || activities || ',' LIKE '%,running,%'
-- 값이 없으면 빈 문자열이 아니라 NULL 입니다 — "안 골랐다" 와 "빈 값을 골랐다"
-- 를 구분할 이유가 없고, NULL 이 그 뜻을 더 정확히 담습니다.
ALTER TABLE launch_notify ADD COLUMN activities TEXT;

